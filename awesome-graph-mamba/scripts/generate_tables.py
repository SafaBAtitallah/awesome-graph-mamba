def build_tables(data: dict, resolved: list[dict]) -> "OrderedDict[str, Table]":
    tables: "OrderedDict[str, Table]" = OrderedDict()
    for fn in TABLE_BUILDERS:
        tb = fn(data, resolved)
        tables[tb.id] = tb
    for spec in data["results"]:
        tb = t_performance(data, resolved, spec)
        tables[tb.id] = tb
