def index_outputs(tables: "OrderedDict[str, Table]") -> dict[Path, str]:
    md = ["# Comparison tables", "",
          "All tables are generated from `data/` by `scripts/generate_tables.py`. Each is available in three formats.", "",
          "| Table | Description | Markdown | LaTeX | CSV |", "| :--- | :--- | :---: | :---: | :---: |"]
    for tid, tb in tables.items():
        md.append(f"| {tb.title} | {md_text(tb.caption)[:160]}{'…' if len(tb.caption) > 160 else ''} | "
                  f"[md](markdown/{tid}.md) | [tex](latex/{tid}.tex) | [csv](csv/{tid}.csv) |")
    md += ["", "## Using the LaTeX tables", "", "```latex", "\\usepackage{booktabs,longtable,multirow,array,graphicx,amsmath,pifont}",
           "\\newcommand{\\cmark}{\\ding{51}}", "\\input{tables/latex/unified_taxonomy}", "```", "",
           "`tables/latex/all_tables.tex` is a compilable demo document that inputs every table."]
    all_tex = ["% Generated by scripts/generate_tables.py -- compilable demo of all tables.",
               "\\documentclass[10pt]{article}", "\\usepackage[margin=1.5cm,landscape]{geometry}",
               "\\usepackage[utf8]{inputenc}", "\\usepackage[T1]{fontenc}",
               "\\usepackage{booktabs,longtable,multirow,array,graphicx,amsmath,pifont,amssymb,url}", "\\newcommand{\\cmark}{\\ding{51}}",
               "\\begin{document}"]
    all_tex += [f"\\input{{{tid}}}\\clearpage" for tid in tables]
    all_tex += ["\\bibliographystyle{plain}", "\\bibliography{../../source/references}", "\\end{document}"]
    return {TABLES / "README.md": "\n".join(md) + "\n", TABLES / "latex" / "all_tables.tex": "\n".join(all_tex) + "\n"}


def table_outputs(data: dict, resolved: list[dict]) -> tuple[dict[Path, str], "OrderedDict[str, Table]"]:
    tables = build_tables(data, resolved)
    out: dict[Path, str] = {}
    for tb in tables.values():
        out.update(tb.outputs())
    out.update(index_outputs(tables))
    return out, tables


