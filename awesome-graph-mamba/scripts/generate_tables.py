#!/usr/bin/env python3
"""Generate the scientific comparison tables from the paper database.

Every table is rendered three times from the same in-memory object:

* ``tables/markdown/<id>.md`` – GitHub-ready Markdown
* ``tables/latex/<id>.tex``   – booktabs LaTeX with BibTeX ``\\cite`` keys
* ``tables/csv/<id>.csv``     – flat CSV for further analysis

Rules enforced here (see README, "Table conventions"):
missing values are rendered ``NR``; performance numbers are only placed
side by side when the survey reports them from the same source paper
and protocol; derived tables state that they are derived.
"""
from __future__ import annotations

import csv
import io
import re
import sys
from collections import Counter, OrderedDict
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import NR, TABLES, csv_text, md_text, tex_text  # noqa: E402
from database import SETTING_ORDER, lookup  # noqa: E402

CHECK_MD, CHECK_TEX = "✓", r"\cmark"


# ---------------------------------------------------------------------------
# Table model and renderers
# ---------------------------------------------------------------------------
@dataclass
class Cell:
    md: str
    tex: str
    csv: str

    @classmethod
    def text(cls, s: Any) -> "Cell":
        return cls(md_text(s), tex_text(s), csv_text(s))

    @classmethod
    def check(cls, flag: bool) -> "Cell":
        return cls(CHECK_MD if flag else "", CHECK_TEX if flag else "", "1" if flag else "0")

    @classmethod
    def model(cls, name: str, key: str | None, link: str | None = None, marks: str = "") -> "Cell":
        md = md_text(name) + marks
        if link and link != NR:
            md = f"[{md_text(name)}]({link}){marks}"
        tex = tex_text(name) + tex_text(marks) if marks else tex_text(name)
        if key:
            tex += "~\\cite{" + key + "}"
        return cls(md, tex, csv_text(name))


_REF_NAMES = {"tab": "Table~\\ref", "fig": "Fig.~\\ref", "sec": "Section~\\ref", "subsec": "Section~\\ref",
              "eq": "Eq.~\\eqref", "app": "Appendix~\\ref"}


def tex_refs(s: str) -> str:
    """Turn manuscript labels (tab:x, sec:x, ...) in already-escaped LaTeX into cross-references."""
    def rep(m):
        label = (m.group(1) + ":" + m.group(2)).replace("\\_", "_")
        return _REF_NAMES[m.group(1)] + "{" + label + "}"
    return re.sub(r"\b(tab|fig|subsec|sec|eq|app):((?:[A-Za-z0-9-]|\\_)+)", rep, s)


def C(x: Any) -> Cell:
    return x if isinstance(x, Cell) else Cell.text(x)


@dataclass
class Table:
    id: str
    title: str
    caption: str
    headers: list[str]
    colspec: str
    rows: list = field(default_factory=list)  # list[list[Cell]] or ("group", label)
    notes: list[str] = field(default_factory=list)
    long: bool = False
    group_header: str = "Group"
    csv_extra_headers: list[str] | None = None
    md_align: list[str] | None = None
    tex_head: str | None = None  # optional raw LaTeX header (multi-row column groups)

    def add(self, cells: list[Any]) -> None:
        self.rows.append([C(c) for c in cells])

    def group(self, label: str) -> None:
        self.rows.append(("group", label))

    # -- Markdown ---------------------------------------------------------
    def to_markdown(self) -> str:
        n = len(self.headers)
        align = self.md_align or [":---"] * n
        out = [f"## {self.title}", "", f"*{md_text(self.caption)}*", ""]
        out.append("| " + " | ".join(self.headers) + " |")
        out.append("| " + " | ".join(align) + " |")
        for r in self.rows:
            if isinstance(r, tuple):
                out.append("| **" + md_text(r[1]) + "** |" + " |" * (n - 1))
            else:
                out.append("| " + " | ".join(c.md for c in r) + " |")
        if self.notes:
            out.append("")
            out += [f"> {md_text(nn)}  " for nn in self.notes]
        out.append("")
        out.append(f"<sub>Generated by `scripts/generate_tables.py` from `data/`. Do not edit by hand. "
                   f"Formats: [LaTeX](../latex/{self.id}.tex) · [CSV](../csv/{self.id}.csv)</sub>")
        return "\n".join(out) + "\n"

    # -- LaTeX ------------------------------------------------------------
    def to_latex(self) -> str:
        n = len(self.headers)
        head = self.tex_head or (" & ".join("\\textbf{" + tex_text(h.replace("**", "")) + "}" for h in self.headers) + " \\\\")
        trace = re.findall(r"manuscript ([^)]*)\)", self.caption)
        caption = re.sub(r"\s*\(manuscript [^)]*\)", "", self.caption)
        body = []
        for r in self.rows:
            if isinstance(r, tuple):
                body.append("\\midrule")
                body.append(f"\\multicolumn{{{n}}}{{l}}{{\\textbf{{{tex_text(r[1])}}}}} \\\\")
                body.append("\\midrule")
            else:
                body.append(" & ".join(c.tex for c in r) + " \\\\")
        notes = ""
        if self.notes:
            notes = "\n\\par\\vspace{1mm}{\\footnotesize " + tex_refs(" ".join(tex_text(x) for x in self.notes)) + "}"
        hdr = (f"% Generated by scripts/generate_tables.py -- do not edit by hand.\n"
               + (f"% Traceability: manuscript {trace[0]}\n" if trace else "")
               +
               f"% Requires: booktabs, longtable, multirow, array, graphicx, amsmath, pifont (\\cmark = \\ding{{51}}).\n")
        if self.long:
            return (hdr + f"\\begingroup\\scriptsize\\setlength{{\\tabcolsep}}{{3pt}}\n"
                    f"\\begin{{longtable}}{{{self.colspec}}}\n"
                    f"\\caption{{{tex_refs(tex_text(caption))}}}\\label{{tab:repo-{self.id}}}\\\\\n"
                    f"\\toprule\n{head}\n\\midrule\n\\endfirsthead\n"
                    f"\\toprule\n{head}\n\\midrule\n\\endhead\n\\bottomrule\n\\endlastfoot\n"
                    + "\n".join(body).replace("\\midrule\n\\multicolumn", "\\multicolumn", 1)
                    + f"\n\\end{{longtable}}{notes}\n\\endgroup\n")
        body_txt = "\n".join(body)
        if body_txt.startswith("\\midrule\n"):
            body_txt = body_txt[len("\\midrule\n"):]
        return (hdr + "\\begin{table*}[htbp]\n\\centering\n"
                f"\\caption{{{tex_refs(tex_text(caption))}}}\n\\label{{tab:repo-{self.id}}}\n"
                "\\scriptsize\n\\setlength{\\tabcolsep}{3pt}\n\\renewcommand{\\arraystretch}{1.15}\n"
                f"\\resizebox{{\\textwidth}}{{!}}{{%\n\\begin{{tabular}}{{{self.colspec}}}\n\\toprule\n{head}\n\\midrule\n"
                f"{body_txt}\n\\bottomrule\n\\end{{tabular}}}}{notes}\n\\end{{table*}}\n")

    # -- CSV --------------------------------------------------------------
    def to_csv(self) -> str:
        buf = io.StringIO()
        w = csv.writer(buf, lineterminator="\n")
        has_groups = any(isinstance(r, tuple) for r in self.rows)
        heads = [h.replace("**", "") for h in (self.csv_extra_headers or self.headers)]
        w.writerow(([self.group_header] if has_groups else []) + heads)
        g = ""
        for r in self.rows:
            if isinstance(r, tuple):
                g = r[1]
                continue
            w.writerow(([csv_text(g)] if has_groups else []) + [c.csv for c in r])
        return buf.getvalue()

    def outputs(self) -> dict[Path, str]:
        return {
            TABLES / "markdown" / f"{self.id}.md": self.to_markdown(),
            TABLES / "latex" / f"{self.id}.tex": self.to_latex(),
            TABLES / "csv" / f"{self.id}.csv": self.to_csv(),
        }


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def marks(rec: dict) -> str:
    m = ""
    if rec.get("precursor"):
        m += "†"
    if rec.get("multimodal"):
        m += "◆"
    if rec["verification"]["status"] == "needs_verification":
        m += "⚠"
    return m


def model_cell(rec: dict, with_marks: bool = True) -> Cell:
    return Cell.model(rec["model"], rec["key"], rec["primary_link"], marks(rec) if with_marks else "")


def by_key(resolved: list[dict]) -> dict[str, dict]:
    return {r["key"]: r for r in resolved}


LEGEND_MARKS = ("Markers: † structured-SSM precursor without input-dependent selection; ◆ multimodal input; "
                "⚠ record flagged for author verification (see docs/FLAGS.md). NR = not reported in the survey.")


