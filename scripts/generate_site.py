#!/usr/bin/env python3
"""Generate the GitHub Pages literature explorer (``docs/index.html``).

The page is fully self-contained: the resolved paper database, the
manuscript-derived taxonomy definitions (``data/taxonomy.yaml``) and every
comparison table (with its exact CSV text) are embedded as JSON, so it
works on GitHub Pages, offline, or from a local file. ``docs/comparison.html``
is kept as a redirect to the tables section for existing links. Both
files are regenerated by ``build.py`` and checked for staleness by
``validate.py`` like every other output.
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import DOCS  # noqa: E402
from database import lookup  # noqa: E402
from generate_catalogue import anchor, page_for  # noqa: E402
from generate_tables import CHECK_MD, LEGEND_MARKS, build_tables  # noqa: E402

TEMPLATE = Path(__file__).resolve().parent / "site_template.html"
KEEP = ["key", "model", "aliases", "title", "authors", "year", "venue", "doi", "arxiv", "url", "search_link", "code",
        "roles", "precursor", "multimodal", "taxonomy", "application", "methodology", "contributions", "complexity",
        "efficiency", "expressivity", "datasets", "result_tables", "advantages", "limitations", "manuscript_sections",
        "verification"]
MD_LINK = re.compile(r"^\[(.+?)\]\((\S+?)\)(.*)$")
MARKS = "†◆⚠"

REDIRECT = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Comparison tables — Exploring Graph Mamba</title>
<meta http-equiv="refresh" content="0; url=./#tables">
<link rel="canonical" href="./#tables">
</head>
<body>
<p>The comparison tables are now part of the explorer: <a href="./#tables">open the comparison tables</a>.</p>
</body>
</html>
"""


def table_cell(c) -> dict:
    """One rendered cell for the site: plain text (+ link and survey markers for model cells)."""
    if c.md == CHECK_MD:
        return {"t": "✓"}
    if c.md == "" and c.csv in ("", "0"):
        return {"t": ""}
    cell = {"t": c.csv}
    m = MD_LINK.match(c.md)
    if m:
        cell["href"] = m.group(2)
    tail = c.md[len(c.md.rstrip(MARKS)):]
    if tail and not c.csv.endswith(tail):
        cell["t"] += tail
    return cell


def table_payload(tb) -> dict:
    return {
        "id": tb.id, "title": tb.title, "caption": tb.caption, "notes": tb.notes,
        "headers": [h.replace("**", "") for h in tb.headers],
        "rows": [{"group": r[1]} if isinstance(r, tuple) else [table_cell(c) for c in r] for r in tb.rows],
        "csv": tb.to_csv(),
    }


def site_outputs(data: dict, resolved: list[dict], tables=None) -> dict[Path, str]:
    tx = data["taxonomy"]
    lk = lookup(tx)
    if tables is None:
        tables = build_tables(data, resolved)
    base = tx["survey"].get("repository", "").rstrip("/") + "/blob/main/"
    papers = [{k: r[k] for k in KEEP} for r in resolved]
    payload = {
        "papers": papers,
        "labels": {k: lk[k] for k in ("setting", "pattern", "domain", "subdomain", "level", "type")},
        "subdomains": [s for d in tx["application_domains"] for s in d["subdomains"]],
        "roleShort": {"taxonomy": "Architecture (D1–D4)", "application": "Application", "discussed": "Discussed in Sec. 7"},
        "counts": {r: sum(r in p["roles"] for p in resolved) for r in ("taxonomy", "application", "discussed")},
        "repoBase": base,
        "repoPages": {r["key"]: f"{base}papers/{page_for(r)}#{anchor(r)}" for r in resolved},
        # Manuscript-derived definitions, transcribed verbatim in data/taxonomy.yaml.
        "survey": {k: tx["survey"][k] for k in ("title", "short_title", "venue", "authors")},
        "researchQuestions": tx["research_questions"],
        "dimensions": tx["dimensions"],
        "settings": tx["graph_settings"],
        "patterns": tx["design_patterns"],
        "domains": [{"id": d["id"], "label": d["label"], "subdomains": [s["id"] for s in d["subdomains"]]}
                    for d in tx["application_domains"]],
        "abbreviations": tx["abbreviations"],
        "legendMarks": LEGEND_MARKS,
        "tables": [table_payload(tb) for tb in tables.values()],
    }
    blob = json.dumps(payload, ensure_ascii=False, sort_keys=True)
    payload["generated"] = "data version " + hashlib.sha256(blob.encode()).hexdigest()[:10]
    js = json.dumps(payload, ensure_ascii=False).replace("</", "<\\/")
    html = TEMPLATE.read_text(encoding="utf-8").replace("__DATA__", js)
    return {DOCS / "index.html": html, DOCS / "comparison.html": REDIRECT}


if __name__ == "__main__":
    from build import build

    build(only=["site"])
